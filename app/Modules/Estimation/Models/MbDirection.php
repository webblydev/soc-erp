<?php

namespace App\Modules\Estimation\Models;

use App\Support\AuditTrail\Auditable;
use App\Support\Lookups\HasCodeLookup;
use App\Support\Lookups\IsLookup;
use Database\Factories\Estimation\MbDirectionFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Attributes\UseFactory;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;

/**
 * Who bills on a measurement: SOC to the customer, or a vendor to SOC (07, spec E2).
 *
 * @property int $id
 * @property string $code
 * @property string $name
 * @property string|null $color
 * @property int $sort_order
 * @property bool $is_active
 * @property bool $is_system
 */
#[Fillable(['code', 'name', 'description', 'sort_order', 'color', 'is_active', 'is_system'])]
#[UseFactory(MbDirectionFactory::class)]
class MbDirection extends Model
{
    /** @use HasFactory<MbDirectionFactory> */
    use Auditable, HasCodeLookup, HasFactory, IsLookup;

    public const CUSTOMER = 'CUSTOMER';

    public const VENDOR = 'VENDOR';
}
